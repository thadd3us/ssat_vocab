#!/bin/sh
# Wraps the data files the page needs into .js files it can load with <script> tags,
# because a page opened straight from disk (file://) isn't allowed to fetch() them.
#   web/ssat_vocab.jsonl       -> web/words.js                 (the JSONL text, verbatim)
#   web/sounds/kaching.wav     -> web/sounds/kaching.js        (a base64 data: URL)
#   web/sounds/words/*.mp3     -> web/sounds/pronunciations.js (word -> base64 data: URL)
# Edit the .jsonl / .wav, then run this (scripts/make_pronunciations.mjs records the .mp3s
# and runs it too). tests/assets.test.js fails if they drift apart.
set -eu
cd "$(dirname "$0")/../web"

if grep -q '[`\\]\|\${' ssat_vocab.jsonl; then
  echo "ssat_vocab.jsonl contains \` or \\ or \${, which can't go in a JS template string" >&2
  exit 1
fi
{
  echo "// Generated by scripts/embed_assets.sh from ssat_vocab.jsonl. Edit that file, then re-run the script."
  echo "(globalThis.WB ||= {}).WORDS_JSONL = String.raw\`"
  cat ssat_vocab.jsonl
  echo "\`;"
} > words.js

{
  echo "// Generated by scripts/embed_assets.sh from kaching.wav (see README.md). Don't edit."
  printf '(globalThis.WB ||= {}).KACHING_URL = "data:audio/wav;base64,%s";\n' "$(base64 < sounds/kaching.wav | tr -d '\n')"
} > sounds/kaching.js

{
  echo "// Generated by scripts/embed_assets.sh from sounds/words/*.mp3 (see scripts/make_pronunciations.mjs). Don't edit."
  echo "(globalThis.WB ||= {}).PRONUNCIATIONS = {"
  for f in sounds/words/*.mp3; do
    w=$(basename "$f" .mp3)
    printf '"%s": "data:audio/mpeg;base64,%s",\n' "$w" "$(base64 < "$f" | tr -d '\n')"
  done
  echo "};"
} > sounds/pronunciations.js

echo "web/words.js ($(wc -c < words.js | tr -d ' ') bytes), web/sounds/kaching.js ($(wc -c < sounds/kaching.js | tr -d ' ') bytes), web/sounds/pronunciations.js ($(ls sounds/words/*.mp3 | wc -l | tr -d ' ') words, $(wc -c < sounds/pronunciations.js | tr -d ' ') bytes)"
