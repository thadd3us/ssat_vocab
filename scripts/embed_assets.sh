#!/bin/sh
# Wraps the two data files the page needs into .js files it can load with <script>
# tags, because a page opened straight from disk (file://) isn't allowed to fetch() them.
#   web/ssat_vocab_410.jsonl  -> web/words.js           (the JSONL text, verbatim)
#   web/sounds/kaching.wav    -> web/sounds/kaching.js  (a base64 data: URL)
# Edit the .jsonl / .wav, then run this. tests/assets.test.js fails if they drift apart.
set -eu
cd "$(dirname "$0")/../web"

if grep -q '[`\\]\|\${' ssat_vocab_410.jsonl; then
  echo "ssat_vocab_410.jsonl contains \` or \\ or \${, which can't go in a JS template string" >&2
  exit 1
fi
{
  echo "// Generated by scripts/embed_assets.sh from ssat_vocab_410.jsonl. Edit that file, then re-run the script."
  echo "(globalThis.WB ||= {}).WORDS_JSONL = String.raw\`"
  cat ssat_vocab_410.jsonl
  echo "\`;"
} > words.js

{
  echo "// Generated by scripts/embed_assets.sh from kaching.wav (see README.md). Don't edit."
  printf '(globalThis.WB ||= {}).KACHING_URL = "data:audio/wav;base64,%s";\n' "$(base64 < sounds/kaching.wav | tr -d '\n')"
} > sounds/kaching.js

echo "web/words.js ($(wc -c < words.js | tr -d ' ') bytes), web/sounds/kaching.js ($(wc -c < sounds/kaching.js | tr -d ' ') bytes)"
